'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'catalog-store.js'),'utf8');
const builtins=[{id:'teaching',title:'Headmaster',post:'Education Department',category:'Education',subjects:['Pedagogy'],ready:true}];
const scope={window:{LAMA_PPSC_JOBS:builtins},Event:class{constructor(type){this.type=type}}};
vm.runInNewContext(code,scope,{timeout:1500});
const catalog=scope.window.LamaPpscJobStore;
assert.ok(catalog);
catalog.mergeRows([{id:'new-post',title:'Assistant Education Officer',post:'Education Department',category:'Education',subjects:['English','Pedagogy'],is_published:true,vacancy_status:'unverified',priority_order:3}]);
assert.equal(builtins.length,2,'new published job appears');
assert.equal(builtins[1].ready,false,'adding a job cannot claim a paper is ready');
catalog.mergeRows([{id:'new-post',title:'Draft Post',post:'Education Department',category:'Education',subjects:['English'],is_published:false}]);
assert.equal(builtins.length,1,'unpublished managed job does not appear');
catalog.mergeRows([{id:'teaching',title:'School Heads',post:'Education Department',category:'Education',subjects:['Leadership'],is_published:true,ready:false}]);
assert.equal(builtins[0].title,'School Heads');
assert.equal(builtins[0].ready,true,'existing paper availability preserved');
catalog.mergeRows([{id:'bad id!',title:'Invalid',post:'Education Department',category:'Education',subjects:['English'],is_published:true}]);
assert.equal(builtins.length,1,'invalid IDs rejected');
const adminHtml=fs.readFileSync(path.join(__dirname,'admin.html'),'utf8');
const adminJs=fs.readFileSync(path.join(__dirname,'admin-jobs.js'),'utf8');
assert.ok(adminHtml.includes('id="jobForm"'),'admin editor exists');
assert.ok(adminJs.includes('adminSaveJob'),'admin editor uses authenticated API');
console.log('Dynamic job catalog regression tests: all passed');
