'use strict';
/* Structural print-layout regression; a real mobile/PDF print review remains a separate release gate. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=__dirname;
const page=fs.readFileSync(path.join(root,'print.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const section=(which)=>{const start=page.indexOf(which);assert.ok(start>=0,'missing media section '+which);const end=page.indexOf('\n}',start);assert.ok(end>start,'unclosed media section '+which);return page.slice(start,end+2);};
const print=section('@media print{'),mobile=section('@media screen and (max-width:850px){');
assert.match(page,/@page\{size:A4 portrait;margin:10mm\}/,'page must use physical A4 format');
assert.match(print,/\.questions\{column-count:2!important/,'actual PDF/print must have TWO question columns');
assert.match(mobile,/\.questions\{column-count:1\}/,'mobile reading preview remains legible');
assert.match(print,/\.choices\{grid-template-columns:1fr!important/,'printed answers must fit within narrow paper columns');
assert.match(print,/\.toolbar\{display:none!important\}/,'print toolbar must not appear in PDF');
assert.match(print,/\.sheet\{width:auto!important/,'printed paper must respect the A4 printable width');
assert.match(page,/\.head\{display:grid;grid-template-columns:minmax\(0,1fr\) 48mm/,'heading has stable logo/title and meta allocation');
assert.match(page,/class="brand".*class="academy-identity"/,'brand text and logo must form an unbroken group');
assert.match(page,/class="paper-title" id="paperPrintTitle"/,'full paper name needs its own full-width row');
assert.match(page,/getElementById\('paperPrintTitle'\)\.textContent=paper\.title/,'paper title must be dynamically populated');
assert.match(page,/getElementById\('paperPrintMeta'\)\.textContent=paper\.questions\.length/,'side metadata should show compact counts, not a long title');
assert.match(page,/src="\.\/assets\/lama-ppsc-approved-192\.png"/,'use official academy print logo');
assert.ok(fs.existsSync(path.join(root,'assets/lama-ppsc-approved-192.png')),'academy logo asset missing');
assert.match(page,/class="watermark"/);
assert.ok(fs.existsSync(path.join(root,'assets/lama-ppsc-approved-512.png')),'watermark asset missing');
assert.match(page,/Print \/ Save PDF/);
assert.match(page,/window\.print\(\)/);
assert.match(page,/candidate.*Name:.*Roll No:.*Date:/s,'candidate detail fields remain visible');
assert.match(page,/root\.innerHTML=paper\.questions\.map/,'question renderer must remain connected to paper data');
assert.match(page,/q\.options\.map/,'question choices must render');
assert.ok(!/root\.innerHTML=.{0,150}q\.answer/.test(page),'question-only print must not reveal answer keys');
assert.ok(sw.includes("'./print.html'"),'offline service worker must include print view');
assert.ok(sw.includes("'./assets/lama-ppsc-approved-192.png'"),'offline logo must be cached');
assert.match(sw,/lama-ppsc-preview-v\d+/,'offline cache must remain versioned');
console.log('PPSC A4 paper layout: professional responsive header, separate paper title, true two-column print, answer legibility, offline logo and question-only renderer checks passed');
