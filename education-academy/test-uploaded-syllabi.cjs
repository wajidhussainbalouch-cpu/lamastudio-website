'use strict';
/* Uploaded PPSC screenshots are transcription evidence, not recruitment-live status or independently authenticated PDF. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=__dirname;
const manifest=JSON.parse(fs.readFileSync(path.join(root,'PPSC_SCREENSHOT_SYLLABI_2026.json'),'utf8'));
const context={window:{},URLSearchParams};
vm.runInNewContext(fs.readFileSync(path.join(root,'jobs.js'),'utf8'),context,{timeout:2000,filename:'jobs.js'});
vm.runInNewContext(fs.readFileSync(path.join(root,'job-catalog-ui.js'),'utf8'),context,{timeout:2000,filename:'job-catalog-ui.js'});
const jobs=context.window.LAMA_PPSC_JOBS,catalog=context.window.LamaAcademyJobCatalog;
assert.equal(manifest.jobs.length,10,'ten supplied screenshot postings must be cataloged');
assert.equal(new Set(manifest.jobs.map(x=>x.id)).size,10,'unique job IDs');
assert.equal(new Set(jobs.map(x=>x.id)).size,jobs.length,'no repeated website job IDs');
assert.ok(jobs.some(x=>x.id==='teaching'&&x.ready),'completed school-head paper family preserved');
assert.ok(jobs.some(x=>x.id==='information-officer'),'prior Information Officer category preserved');
assert.ok(jobs.some(x=>x.id==='junior-clerk'&&x.caseNo==='57J2024'),'historical generic Junior Clerk must not be silently replaced');
const byId=new Map(jobs.map(x=>[x.id,x]));
for(const [i,entry] of manifest.jobs.entries()){
 const job=byId.get(entry.id),selected=catalog.resolve(entry.id);
 assert.ok(job&&selected,'missing uploaded case '+entry.id);
 if(entry.id==='junior-clerk-bahawalpur-bor')assert.ok(job.ready,'Junior Clerk Bahawalpur first practice paper must be available');
 else assert.ok(!job.ready,'other uploaded syllabus tracks cannot claim a paper before publication '+entry.id);
 assert.equal(job.priority,true,'uploaded syllabus must be prioritized '+entry.id);
 assert.equal(job.priorityOrder,i+2,'prioritized preparation queue must have stable order '+entry.id);
 assert.equal(job.title,entry.title);
 assert.equal(job.caseNo,entry.caseNo);
 assert.ok(Array.isArray(job.subjects)&&job.subjects.length>0);
 assert.ok(selected.syllabusEvidence,'dropdown failed to carry screenshot syllabus '+entry.id);
 assert.equal(selected.syllabusEvidence.status,'screenshot-transcribed');
 const e=entry.syllabusEvidence;
 assert.equal(e.status,'screenshot-transcribed');
 assert.ok(e.source.includes('PPSC')&&e.source.includes('original PDF not independently archived'));
 assert.ok(Array.isArray(e.sections)&&e.sections.length>=1);
 const percentages=e.sections.map(p=>p.percent).filter(x=>x!==null);
 if(percentages.length===e.sections.length)assert.equal(percentages.reduce((a,b)=>a+b,0),100,'weights must total 100 for '+entry.id);
 if(e.marks!==null)assert.equal(e.marks,100,'100-mark screenshot case '+entry.id);
 if(e.minutes!==null)assert.equal(e.minutes,90,'90-minute screenshot case '+entry.id);
}
const percentages=id=>byId.get(id).syllabusEvidence.sections.map(p=>p.percent);
assert.deepEqual(Array.from(percentages('junior-clerk-bahawalpur-bor')),[80,20]);
assert.deepEqual(Array.from(percentages('junior-clerk-faisalabad-bor')),[80,20]);
assert.deepEqual(Array.from(percentages('secretary-a-market-pamra')),[60,40]);
assert.deepEqual(Array.from(percentages('secretary-b-market-pamra')),[60,40]);
assert.deepEqual(Array.from(percentages('assistant-microbiologist-pfa')),[100]);
assert.deepEqual(Array.from(percentages('municipal-engineering-lg')),[100]);
assert.deepEqual(Array.from(percentages('chief-officer-regulations-lg')),[null,null],'do not invent Act/general weights');
assert.equal(byId.get('laboratory-technician-auqaf').syllabusEvidence.minutes,null,'lab test duration not stated');
assert.equal(byId.get('laboratory-technician-auqaf').syllabusEvidence.marks,null,'lab test marks not stated');
const finder=fs.readFileSync(path.join(root,'syllabus-finder.js'),'utf8');
assert.ok(finder.includes('chosen.syllabusEvidence')&&finder.includes('Screenshot syllabus distribution'),'syllabus finder must visibly render uploaded percent allocation');
const shell=fs.readFileSync(path.join(root,'shell.js'),'utf8');
assert.ok(shell.includes('PPSC syllabus supplied · Paper pending'),'dashboard must distinguish supplied syllabus from published paper');
console.log('Ten uploaded PPSC syllabus screenshots: separate case IDs, 80/20 and 60/40 patterns, protected case details and paper-priority regression passed');
