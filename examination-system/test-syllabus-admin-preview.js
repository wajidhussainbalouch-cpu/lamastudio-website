'use strict';
const assert=require('node:assert/strict');
const {buildAdminPreview}=require('./syllabus-admin-preview');
const {createDraftDivision}=require('./syllabus-division-draft');
const {makeEnglishCalendar}=require('./syllabus-school-calendar-2026');
const catalog=require('./catalogs/english-class-5.json');
const division=createDraftDivision(catalog);
const original=JSON.stringify(division);
const calendar=makeEnglishCalendar({1:1,2:1,3:1,4:1,5:1},['2026-05-01','2026-08-25','2026-11-09']);
const preview=buildAdminPreview({division,calendar});
assert.equal(preview.readOnly,true);
assert.equal(preview.approvalReady,false);
assert.equal(preview.rows.length,74);
assert.equal(preview.rows[0].lessonId,'EN5-U01-READING');
assert.equal(preview.rows[0].difficulty,'moderate');
assert.equal(preview.requiredUnfinishedPeriods,176);
assert.equal(preview.feasible,false);
assert.ok(preview.shortfall>0);
assert.ok(preview.warnings.some(w=>w.includes('public holidays')));
assert.equal(JSON.stringify(division),original);
const altered=buildAdminPreview({division,calendar:{...calendar,holidays:[...calendar.holidays,'2026-04-02']}});
assert.deepEqual(altered.rows.map(r=>r.lessonId),preview.rows.map(r=>r.lessonId));
assert.notDeepEqual(altered.rows.map(r=>r.dates),preview.rows.map(r=>r.dates));
assert.equal(JSON.stringify(division),original);
console.log('read-only admin preview tests passed');
