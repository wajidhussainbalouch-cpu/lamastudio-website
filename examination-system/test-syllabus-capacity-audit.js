'use strict';
const assert=require('node:assert/strict');
const {auditCapacity}=require('./syllabus-capacity-audit');
const {makeEnglishCalendar}=require('./syllabus-school-calendar-2026');
const {createDraftDivision}=require('./syllabus-division-draft');
const catalog=require('./catalogs/english-class-5.json');
const lessons=createDraftDivision(catalog).lessons;
const cal=makeEnglishCalendar({1:1,2:1,3:1,4:1,5:1});
const report=auditCapacity({lessons,calendar:cal});
assert.equal(report.requiredPeriods,176);
assert.equal(report.feasible,false);
assert.equal(report.shortfall,176-report.availablePeriods);
assert.equal(report.availablePeriods,Object.values(report.months).reduce((n,m)=>n+m.availablePeriods,0));
const holiday=auditCapacity({lessons,calendar:{...cal,holidays:['2026-05-01']}});
assert.equal(holiday.availablePeriods,report.availablePeriods-1);
const fridayOff=auditCapacity({lessons,calendar:makeEnglishCalendar({1:1,2:1,3:1,4:1,5:0})});
assert.ok(fridayOff.availablePeriods<report.availablePeriods);
assert.deepEqual(lessons.map(l=>l.lessonId),createDraftDivision(catalog).lessons.map(l=>l.lessonId));
assert.throws(()=>auditCapacity({lessons:[lessons[0],lessons[0]],calendar:cal}),/duplicate/);
console.log('capacity audit tests passed',report.availablePeriods,report.shortfall);
