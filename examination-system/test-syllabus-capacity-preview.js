'use strict';
const assert=require('node:assert/strict');
const {buildCapacityPreview}=require('./syllabus-capacity-preview');
const {createDraftDivision}=require('./syllabus-division-draft');
const {makeEnglishCalendar}=require('./syllabus-school-calendar-2026');
const catalog=require('./catalogs/english-class-5.json');
const division=createDraftDivision(catalog);
const calendar=makeEnglishCalendar({0:0,1:1,2:1,3:1,4:1,5:1,6:0});
const before=JSON.stringify(division);
const result=buildCapacityPreview({division,calendar});
assert.equal(result.lessonCount,74);
assert.equal(result.requiredPeriods,176);
assert.equal(result.feasible,false);
assert.equal(result.missingPeriods,176-result.availablePeriods);
assert.ok(result.warnings.some(x=>x.includes('Insufficient')));
assert.ok(result.warnings.some(x=>x.includes('not approved')));
assert.equal(JSON.stringify(division),before);
const two=buildCapacityPreview({division:{status:'approved',lessons:[{lessonId:'a',estimatedPeriods:1}]},calendar});
assert.equal(two.feasible,true);
assert.equal(two.warnings.length,0);
assert.throws(()=>buildCapacityPreview({division:{lessons:[]}}),/Missing division\/calendar/);
console.log('Syllabus capacity preview tests passed');
