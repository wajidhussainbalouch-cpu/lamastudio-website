'use strict';
const assert=require('node:assert/strict');
const {evaluateTeachingCapacity}=require('./syllabus-capacity-scenarios');
const {createDraftDivision}=require('./syllabus-division-draft');
const catalog=require('./catalogs/english-class-5.json');
const lessons=createDraftDivision(catalog).lessons;
const results=evaluateTeachingCapacity(lessons);
assert.equal(results.length,3);
assert.equal(results.every(r=>r.requiredPeriods===176),true);
assert.equal(results[0].availablePeriods<results[1].availablePeriods,true);
assert.equal(results[1].availablePeriods<results[2].availablePeriods,true);
assert.equal(results[0].feasible,false);
assert.equal(results[1].feasible,false);
assert.equal(results[2].feasible,true);
const holidayResults=evaluateTeachingCapacity(lessons,{holidays:['2026-04-01','2026-04-02']});
assert.equal(holidayResults[1].availablePeriods,results[1].availablePeriods-2);
assert.equal(holidayResults[1].requiredPeriods,176);
assert.deepEqual(lessons.map(x=>x.lessonId),createDraftDivision(catalog).lessons.map(x=>x.lessonId));
console.log('Teaching capacity scenarios tests passed',results);
