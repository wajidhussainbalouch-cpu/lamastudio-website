'use strict';
const assert=require('node:assert/strict');
const {makeDivisionSnapshot,verifyDivisionSnapshot}=require('./syllabus-division-snapshot');
const {createDraftDivision}=require('./syllabus-division-draft');
const catalog=require('./catalogs/english-class-5.json');
const draft=createDraftDivision(catalog),submitted={...draft,status:'submitted',revision:2};
const scope={schoolId:'s1',classId:'5',subjectId:'English',sessionId:'2026-27'};
const before=JSON.stringify(submitted);
const a=makeDivisionSnapshot({division:submitted,scope,expectedRevision:2});
const b=makeDivisionSnapshot({division:submitted,scope,expectedRevision:2});
assert.equal(a.hash,b.hash);
assert.equal(a.content.lessons.length,74);
assert.equal(verifyDivisionSnapshot(a),true);
assert.equal(JSON.stringify(submitted),before);
a.content.lessons[0].topic='Tampered';
assert.equal(verifyDivisionSnapshot(a),false);
assert.throws(()=>makeDivisionSnapshot({division:draft,scope,expectedRevision:0}),/Submitted/);
assert.throws(()=>makeDivisionSnapshot({division:submitted,scope,expectedRevision:1}),/Revision conflict/);
assert.throws(()=>makeDivisionSnapshot({division:submitted,scope:{...scope,schoolId:''},expectedRevision:2}),/Missing scope/);
const injected={...submitted,lessons:[{...submitted.lessons[0],scheduledDate:'2026-04-01'},...submitted.lessons.slice(1)]};
assert.throws(()=>makeDivisionSnapshot({division:injected,scope,expectedRevision:2}),/Calendar/);
console.log('division snapshot integrity tests passed');
