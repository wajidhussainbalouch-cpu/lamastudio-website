'use strict';
const assert=require('node:assert/strict');
const {SCHOOL_CALENDAR_2026,makeEnglishCalendar}=require('./syllabus-school-calendar-2026');
const {scheduleApprovedDivision}=require('./syllabus-calendar-engine');
const {createDraftDivision}=require('./syllabus-division-draft');
const catalog=require('./catalogs/english-class-5.json');
const lessons=createDraftDivision(catalog).lessons;
assert.equal(lessons.length,74);
const sample=makeEnglishCalendar({1:1,2:1,3:1,4:1,5:1,6:0,0:0});
const result=scheduleApprovedDivision({lessons,calendar:sample});
assert.equal(result.requiredUnfinishedPeriods,176);
assert.equal(result.feasible,false);
assert.equal(result.assignments.some(a=>a.status==='insufficient-capacity'),true);
assert.equal(result.assignments.flatMap(a=>a.slots).some(s=>s.date>='2026-05-22'&&s.date<='2026-08-23'),false);
assert.equal(result.assignments.flatMap(a=>a.slots).some(s=>new Date(s.date+'T00:00:00Z').getUTCDay()===0),false);
assert.equal(result.assignments.flatMap(a=>a.slots).some(s=>new Date(s.date+'T00:00:00Z').getUTCDay()===6),false);
assert.equal(SCHOOL_CALENDAR_2026.revisionStart,'2027-01-01');
assert.throws(()=>makeEnglishCalendar({0:1,1:1}),/Weekend/);
assert.throws(()=>makeEnglishCalendar({1:1,2:1,3:1,4:1,5:2}),/Friday/);
console.log('2026-27 school calendar capacity and closure tests passed',result.availablePeriods);
