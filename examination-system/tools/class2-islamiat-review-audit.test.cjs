"use strict";
const assert=require("node:assert/strict");
const {appendReviewEvent,verifyReviewHistory}=require("./class2-islamiat-review-audit.cjs");
const question={id:"Q1",schoolId:"school-a",approved:false,onlineReady:false,reviewStatus:"draft"};
const actor={id:"teacher-1",schoolId:"school-a",role:"teacher",authenticated:true};
const review={textbookPage:2,sourceBasis:"pctb-page-verified",reviewedBy:"teacher-1",reviewedAt:"2026-11-09T07:00:00Z",verificationNote:"Checked against textbook page two.",answerChecked:true,ageAppropriate:true,duplicateChecked:true};
const args={question,review,actor,schoolId:"school-a",decision:"recommend_approval"};
const first=appendReviewEvent({history:[],...args});
assert.equal(first.length,1);
assert.equal(first[0].sequence,1);
assert.equal(first[0].approved,false);
assert.ok(verifyReviewHistory(first));
const second=appendReviewEvent({history:first,...args,decision:"request_changes"});
assert.equal(second.length,2);
assert.equal(second[1].previousHash,first[0].hash);
assert.ok(verifyReviewHistory(second));
assert.equal(verifyReviewHistory(second.map((e,i)=>i?{...e,verificationNote:"Tampered"}:e)),false);
assert.equal(verifyReviewHistory([second[1],second[0]]),false);
assert.throws(()=>appendReviewEvent({history:second,...args,schoolId:"school-b"}),/same-school|another school/);
assert.throws(()=>appendReviewEvent({history:[{...first[0],hash:"0".repeat(64)}],...args}),/Invalid existing/);
console.log("Review audit chain tests passed");
