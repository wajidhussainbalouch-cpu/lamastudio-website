"use strict";
const assert=require("node:assert/strict");
const {prepareReviewDecision}=require("./class2-islamiat-review-decision.cjs");
const question={id:"Q1",schoolId:"school-a",approved:false,onlineReady:false,reviewStatus:"draft"};
const actor={id:"teacher-1",schoolId:"school-a",role:"teacher",authenticated:true};
const review={textbookPage:2,sourceBasis:"pctb-page-verified",reviewedBy:"teacher-1",reviewedAt:"2026-11-09T07:00:00Z",verificationNote:"Checked against the stated textbook page.",answerChecked:true,ageAppropriate:true,duplicateChecked:true};
const args={question,actor,schoolId:"school-a",review,decision:"recommend_approval"};
const result=prepareReviewDecision(args);
assert.equal(result.decision,"recommend_approval");
assert.equal(result.approved,false);
assert.equal(result.onlineReady,false);
assert.equal(question.approved,false);
assert.throws(()=>prepareReviewDecision({...args,actor:{...actor,schoolId:"school-b"}}),/same-school/);
assert.throws(()=>prepareReviewDecision({...args,actor:{...actor,authenticated:false}}),/same-school/);
assert.throws(()=>prepareReviewDecision({...args,actor:{...actor,role:"student"}}),/same-school/);
assert.throws(()=>prepareReviewDecision({...args,question:{...question,schoolId:"school-b"}}),/school mismatch/);
assert.throws(()=>prepareReviewDecision({...args,review:{...review,reviewedBy:"another"}}),/identity mismatch/);
assert.throws(()=>prepareReviewDecision({...args,review:{...review,textbookPage:null}}),/incomplete/);
assert.throws(()=>prepareReviewDecision({...args,question:{...question,approved:true}}),/Only draft/);
const change=prepareReviewDecision({...args,decision:"request_changes",review:{reviewedBy:"teacher-1",reviewedAt:"2026-11-09T07:00:00Z",verificationNote:"Please correct the answer and reference."}});
assert.equal(change.evidenceValid,false);
assert.equal(change.approved,false);
console.log("Offline review decision tests passed");
