"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"../class2-islamiat-review-preview.html"),"utf8");
const batch=JSON.parse(fs.readFileSync(path.join(__dirname,"../data/class2-islamiat-batch1-500-draft.json"),"utf8"));
assert.equal(batch.questions.length,500);
const q=batch.questions[0];
assert.equal(typeof q.questionId,"string");
assert.equal(typeof q.questionText,"string");
assert.equal(q.reviewStatus,"draft");
assert.equal(q.approved,false);
assert.equal(q.onlineReady,false);
assert.match(html,/typeof q\.questionId==="string"/);
assert.match(html,/typeof q\.questionText==="string"/);
assert.match(html,/q\.reviewStatus!=="draft"/);
assert.match(html,/q\.approved!==false/);
assert.match(html,/q\.onlineReady!==false/);
assert.match(html,/return \{questionId:q\.questionId,questionText:q\.questionText/);
assert.doesNotMatch(html,/fetch\s*\(/);
assert.doesNotMatch(html,/localStorage|sessionStorage/);
console.log("Review preview static contract checks passed (not a browser integration test)");
