"use strict";
const assert=require("node:assert/strict");
const {createReviewStore}=require("./class2-islamiat-review-store.cjs");
const store=createReviewStore();
const question={id:"Q1",schoolId:"school-a",approved:false,onlineReady:false,reviewStatus:"draft"};
const actor={id:"teacher-1",schoolId:"school-a",role:"teacher",authenticated:true};
const review={textbookPage:2,sourceBasis:"pctb-page-verified",reviewedBy:"teacher-1",reviewedAt:"2026-11-09T07:00:00Z",verificationNote:"Checked against textbook page two.",answerChecked:true,ageAppropriate:true,duplicateChecked:true};
const args={question,actor,schoolId:"school-a",review,decision:"recommend_approval"};
const initial=store.read({schoolId:"school-a",questionId:"Q1"});
assert.deepEqual([initial.version,initial.headHash],[0,null]);
const first=store.append({...args,expectedVersion:0,expectedHeadHash:null});
assert.equal(first.version,1);
assert.equal(first.history[0].approved,false);
assert.throws(()=>store.append({...args,expectedVersion:0,expectedHeadHash:null}),/conflict/);
assert.throws(()=>store.append({...args,expectedVersion:1,expectedHeadHash:"bad"}),/conflict/);
first.history[0].verificationNote="tampered copy";
assert.notEqual(store.read({schoolId:"school-a",questionId:"Q1"}).history[0].verificationNote,"tampered copy");
const second=store.append({...args,expectedVersion:1,expectedHeadHash:first.headHash,decision:"request_changes"});
assert.equal(second.version,2);
assert.equal(store.read({schoolId:"school-b",questionId:"Q1"}).version,0);
assert.throws(()=>store.append({...args,actor:{...actor,schoolId:"school-b"},expectedVersion:2,expectedHeadHash:second.headHash}),/same-school/);
console.log("Review store concurrency simulation tests passed");
