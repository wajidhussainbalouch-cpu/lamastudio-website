'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const context={};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'syllabus-draft.gs'),'utf8'),context);
const draft=context.LamaSyllabusDraft.create;
const lesson={date:'2027-03-01',slot:1,lessonId:'L1',lessonTitle:'Counting'};
const input={planId:'P1',sessionId:'2027',classId:'1',subjectId:'Math',scheduled:[lesson]};
const created=draft('school1',input);
assert.equal(created.schoolId,'school1');
assert.equal(created.status,'draft');
assert.equal(created.version,1);
assert.equal(created.scheduled.length,1);
assert.throws(()=>draft('school1',Object.assign({},input,{schoolId:'other'})),/Unsupported draft field/);
assert.throws(()=>draft('school1',Object.assign({},input,{scheduled:[lesson,lesson]})),/Duplicate date and slot/);
assert.throws(()=>draft('school1',Object.assign({},input,{scheduled:[Object.assign({},lesson,{date:'2027-02-30'})]})),/Invalid lesson date/);
assert.throws(()=>draft('school1',Object.assign({},input,{scheduled:[Object.assign({},lesson,{slot:13})]})),/Invalid lesson slot/);
console.log('Syllabus draft validation passed');
