'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const sandbox={};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(__dirname+'/syllabus-readonly-bridge.gs','utf8'),sandbox);
const prepare=sandbox.LamaSyllabusReadonlyBridge.prepare;
const context={schoolId:'school-1',actorId:'admin-1',authenticated:true,examinationGranted:true,canViewSyllabus:true};
const plan={schoolId:'school-1',planId:'plan-1',sessionId:'2026-27',classId:'5',subjectId:'English',status:'published',version:3,scheduled:[{date:'2026-04-01',slot:2,lessonId:'L1',lessonTitle:'Reading'}]};
const original=JSON.stringify(plan);
const view=prepare(plan,context);
assert.equal(view.readOnly,true);
assert.equal(view.immutableDivisionApproved,false);
assert.equal(view.requiresExerciseReview,true);
assert.equal(view.scheduled[0].lessonId,'L1');
assert.equal(JSON.stringify(plan),original);
assert.throws(()=>prepare(plan,{...context,schoolId:'other'}),/Cross-school/);
assert.throws(()=>prepare(plan,{...context,authenticated:false}),/Authenticated/);
assert.throws(()=>prepare(plan,{...context,examinationGranted:false}),/Authenticated/);
assert.throws(()=>prepare(plan,{...context,canViewSyllabus:false}),/Authenticated/);
assert.throws(()=>prepare({...plan,scheduled:[{...plan.scheduled[0],slot:0}]},context),/Invalid stored syllabus lesson/);
assert.throws(()=>prepare({...plan,scheduled:[{...plan.scheduled[0],date:'2026-02-30'}]},context),/Invalid stored syllabus lesson/);
assert.throws(()=>prepare({...plan,scheduled:[{...plan.scheduled[0],lessonTitle:'=SUM(A1:A2)'}]},context),/Invalid stored syllabus lesson/);
assert.throws(()=>prepare({...plan,scheduled:[plan.scheduled[0],{...plan.scheduled[0],lessonId:'L2'}]},context),/Duplicate stored syllabus teaching slot/);
console.log('Apps Script read-only syllabus bridge tests passed');
