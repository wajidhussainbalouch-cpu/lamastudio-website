'use strict';
// Synthetic classes, a fake school name and a fake logo. No API or school data.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const helper=fs.readFileSync(path.join(root,'js/lama-timetable-print.js'),'utf8');
const planning=fs.readFileSync(path.join(root,'js/lama-school-planning.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const sandbox={window:{},Intl,Date,console};
vm.createContext(sandbox);
vm.runInContext(helper,sandbox);
new vm.Script(planning,{filename:'lama-school-planning.js'});
const print=sandbox.window.LamaTimetablePrint;
const school={name:'Government Primary School Shah Sadar Din',logo:'https://example.test/school-logo.png'};
const records=[
 {id:'a',day:'Tuesday',period:2,start:'10:00',end:'10:40',grade:'5',section:'',subject:'Math',teacherName:'Teacher A',room:'Room 5',published:true},
 {id:'b',day:'Monday',period:1,start:'09:00',end:'09:40',grade:'1',section:'A',subject:'Urdu',teacherName:'Teacher B',room:'Room 1',published:true},
 {id:'c',day:'Monday',period:1,start:'09:00',end:'09:40',grade:'5',section:'',subject:'Quran Shareef',teacherName:'Teacher C',room:'Library',published:true},
 {id:'unpub',day:'Wednesday',period:1,start:'09:00',end:'10:00',grade:'1',subject:'Unpublished topic',published:false}
];
const all=print.printMarkup({school,sessionName:'2026-2027',records,scope:'all'});
assert.equal((all.match(/<h1>Government Primary School Shah Sadar Din<\/h1>/g)||[]).length,1);
assert.match(all,/<img class="print-school-logo" src="https:\/\/example\.test\/school-logo\.png"/);
assert.ok(all.indexOf('Government Primary School Shah Sadar Din')<all.indexOf('school-logo.png'),'School name must appear ahead of logo');
assert.ok(all.indexOf('school-logo.png')<all.indexOf('<table'),'School logo must appear before timetable');
assert.match(all,/All Classes — Weekly Timetable/);
for(const subject of ['Math','Urdu','Quran Shareef'])assert.ok(all.includes(subject));
assert.ok(!all.includes('Unpublished topic'),'Unpublished periods must not enter the printed timetable');
assert.ok(all.indexOf('Urdu')<all.indexOf('Math'),'Combined timetable sorted by school day');
assert.match(all,/Academic session: <b>2026-2027<\/b>/);
assert.match(all,/Section A/);
assert.match(all,/Generated by LAMA School Suite/);
const selected=print.printMarkup({school,sessionName:'2026-2027',records,scope:'selected',selectedClass:'5'});
assert.match(selected,/Class 5 — Weekly Timetable/);
assert.match(selected,/Math/);
assert.match(selected,/Quran Shareef/);
assert.ok(!selected.includes('Urdu'),'Class 5 printing must not leak Class 1 periods');
assert.throws(()=>print.printMarkup({school,records,scope:'selected'}),/Choose a class/);
assert.match(selected,/class="school-timetable weekly-matrix"/,'Selected-class print uses a weekly grid');
assert.match(selected,/<th scope="col">Mon<\/th>/,'Weekly grid includes Monday');
assert.match(selected,/<th scope="col">Sat<\/th>/,'Weekly grid includes Saturday');
assert.ok(!selected.includes('<th scope="col">Sun</th>'),'Do not add unused Sunday column');
assert.match(selected,/<th scope="row">P1<\/th>/);
assert.match(selected,/<th scope="row">P2<\/th>/);
assert.match(selected,/09:00 – 09:40/,'Keep timetable times exactly as saved');
assert.match(print.weeklyMatrix([{day:'Sunday',period:1,subject:'Sunday class'}]),/<th scope="col">Sun<\/th>/,'Include Sunday only when the class operates on Sunday');

const grouped=print.printMarkup({school,sessionName:'2026-2027',records,scope:'by-class'});
assert.equal((grouped.match(/<article class="print-class-page">/g)||[]).length,2,'Separate page for each class/section');
assert.equal((grouped.match(/<h1>Government Primary School Shah Sadar Din<\/h1>/g)||[]).length,2,'Repeat full school name on both pages');
assert.equal((grouped.match(/<img class="print-school-logo"/g)||[]).length,2,'Repeat actual logo on both pages');
assert.equal((grouped.match(/Generated by LAMA School Suite/g)||[]).length,2,'Footer on each class page');
assert.ok(grouped.includes('Class 1 · Section A'));
assert.ok(grouped.includes('Class 5'));
const class1=grouped.slice(grouped.indexOf('<h3>Class 1'),grouped.indexOf('Generated by LAMA School Suite'));
assert.match(class1,/Urdu/);
assert.ok(!class1.includes('Quran Shareef'),'A class-specific page must not include another class');
const withCalendar=print.printMarkup({school,records,scope:'all',calendar:true,calendarMonth:'November 2026',calendarContent:'<b>Mon</b>',calendarEvents:'<p>No events</p>'});
assert.match(withCalendar,/Academic Calendar — November 2026/);
assert.ok(!all.includes('print-calendar-block'),'Calendar printing must be optional');
assert.equal(print.safeLogo({logo:'javascript:alert(1)'}),'');
assert.equal(print.safeLogo({logo:'data:image/svg+xml,<svg onload=alert(1)>'}),'');
const malicious=print.printMarkup({school:{name:'<img src=x onerror=alert(1)>',logo:'javascript:alert(1)'},records:[{day:'Monday',grade:'1',subject:'<script>alert(2)</script>'}],scope:'all'});
assert.ok(!malicious.includes('<script>alert(2)</script>'));
assert.ok(!malicious.includes('<img src=x onerror=alert(1)>'));
assert.ok(!malicious.includes('src="javascript:'));
assert.match(html,/@page\{size:A4 portrait/);
assert.match(html,/\.weekly-matrix/,'A4 matrix styles must be present');
assert.match(html,/main > :not\(#printSheet\)\{display:none!important\}/,'Print-only sheet must hide edit forms and status text');
assert.match(html,/id="printScope"/);
assert.match(html,/id="printCalendar"/);
assert.match(html,/id="printSheet"/);
assert.match(html,/src="\.\.\/js\/lama-timetable-print\.js"/);
assert.match(planning,/getActiveSchool\(\)/,'Admin uses stored official school name and logo');
assert.match(planning,/viewGrade/);
assert.match(planning,/class-wise|by-class|printScope/i);
assert.match(planning,/beforeprint/);
assert.match(planning,/printPrepared/);
console.log('PASS: full school name and official logo at top, A4, class-only/all-class/class-per-page print, safe text, calendar option and unchanged source records.');
