'use strict';
const assert=require('node:assert/strict');
const {authorize,studentPaper}=require('./policy.js');
const grant={schoolId:'s1',module:'examination',status:'active',expiresAt:'2027-01-01T00:00:00Z'};
const teacher={verified:true,id:'t1',role:'teacher',schoolId:'s1',classIds:['c1'],subjectIds:['math']};
const resource={schoolId:'s1',classId:'c1',subjectId:'math'};
const check=(p,r,a,g=[grant])=>authorize({principal:p,resource:r,action:a,grants:g,now:Date.parse('2026-11-04T00:00:00Z')});
assert.equal(check(teacher,resource,'exams:author').allowed,true);
assert.equal(check(teacher,{...resource,schoolId:'s2'},'exams:author').reason,'TENANT_MISMATCH');
assert.equal(check(teacher,{...resource,classId:'c2'},'exams:author').reason,'CLASS_MISMATCH');
assert.equal(check(teacher,resource,'exams:author',[]).reason,'ENTITLEMENT_REQUIRED');
assert.equal(check(teacher,resource,'grants:write').reason,'FORBIDDEN');
assert.equal(check({...teacher,verified:false},resource,'exams:author').reason,'UNAUTHENTICATED');
assert.equal(check({verified:true,id:'s1student',role:'student',schoolId:'s1'},{schoolId:'s1',studentId:'other'},'exams:attempt').reason,'STUDENT_MISMATCH');
const p=studentPaper({paperId:'p1',examId:'e1',version:1,questions:[{questionId:'q1',status:'approved',type:'mcq',prompt:'2+2?',options:[{id:'a',text:'4',isCorrect:true}],correctAnswer:'a',answerKey:'secret',marks:1}]});
assert.equal(JSON.stringify(p).includes('correctAnswer'),false);
assert.equal(JSON.stringify(p).includes('isCorrect'),false);
assert.throws(()=>studentPaper({questions:[{questionId:'q2',status:'draft'}]}));
console.log('Platform policy tests passed');
